#!/usr/bin/env node
/**
 * Validate environment variables against env.schema.json.
 *
 *   node scripts/check-env.mjs                 # validate the local env
 *   node scripts/check-env.mjs --scope server  # only the vars the build needs
 *   node scripts/check-env.mjs --remote        # diff Convex vs Vercel vs local
 *   node scripts/check-env.mjs --remote --ci   # same, non-zero exit on drift
 *   node scripts/check-env.mjs --write-example # regenerate .env.example
 *
 * STRICTLY READ-ONLY against remote systems: it lists NAMES, never values, and
 * never writes to Convex or Vercel. An agent "fixing drift" by writing to a
 * production env is the worst possible outcome here.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(readFileSync(join(APP, 'env.schema.json'), 'utf8'));
const args = process.argv.slice(2);
const has = (f) => args.includes(f);

const C = process.stdout.isTTY
  ? { r: '\x1b[31m', g: '\x1b[32m', y: '\x1b[33m', d: '\x1b[2m', b: '\x1b[1m', x: '\x1b[0m' }
  : { r: '', g: '', y: '', d: '', b: '', x: '' };

const isRequired = (v) => v.required !== false && !v.platformProvided && v.homes.length > 0;
/**
 * Whether a var is mandatory in ONE specific home. `requiredIn` narrows this:
 * POLAR_SERVER, for instance, lives in several homes but is only mandatory in
 * the production ones — elsewhere the code's 'sandbox' default is intended, so
 * flagging its absence would be a false positive.
 */
const isRequiredIn = (v, home) =>
  isRequired(v) && (!v.requiredIn || v.requiredIn.includes(home));
const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);

/** Parse a dotenv file into a plain object. Values are never printed. */
function readDotenv(file) {
  const out = {};
  if (!existsSync(file)) return out;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)$/i);
    if (!m) continue;
    let val = m[2].trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[m[1]] = val;
  }
  return out;
}

function localEnv() {
  // Later files win, matching Vite's precedence closely enough for a name check.
  return {
    ...readDotenv(join(APP, '.env')),
    ...readDotenv(join(APP, '.env.local')),
    ...readDotenv(join(APP, '.env.e2e')),
    ...process.env,
  };
}

// ── --write-example ─────────────────────────────────────────────────────────
if (has('--write-example')) {
  const lines = [
    '# Generated by `node scripts/check-env.mjs --write-example` — DO NOT EDIT BY HAND.',
    '# Source of truth: env.schema.json',
    '#',
    '# Copy to .env.local and fill in. Values here are placeholders, never real',
    '# secrets. .env.e2e has its own example file (.env.e2e.example).',
    '',
  ];
  const groups = [
    ['Client (baked into the browser bundle — public by definition)', (v) => v.public],
    ['Vercel server runtime', (v) => !v.public && v.homes.some((h) => h.startsWith('vercel:')) && !v.homes.some((h) => h.startsWith('convex:'))],
    ['Convex deployment', (v) => !v.public && v.homes.some((h) => h.startsWith('convex:')) && !v.dualHome],
    ['Set in BOTH Convex and Vercel — keep them identical', (v) => v.dualHome],
    ['Local / Playwright only', (v) => v.homes.some((h) => h.startsWith('local')) && !v.homes.some((h) => h.startsWith('vercel:') || h.startsWith('convex:'))],
    ['Provided by the platform — do not set', (v) => !!v.platformProvided],
  ];
  const seen = new Set();
  for (const [title, pred] of groups) {
    const vars = schema.vars.filter((v) => !seen.has(v.name) && pred(v));
    if (!vars.length) continue;
    lines.push(`# ── ${title} ${'─'.repeat(Math.max(0, 68 - title.length))}`);
    for (const v of vars) {
      seen.add(v.name);
      if (v.note) for (const l of wrap(v.note, 74)) lines.push(`# ${l}`);
      const placeholder = v.enum ? v.enum.join('|') : v.secret ? 'CHANGE_ME' : '';
      lines.push(`${v.platformProvided ? '# ' : ''}${v.name}=${placeholder}`, '');
    }
  }
  writeFileSync(join(APP, '.env.example'), lines.join('\n').replace(/\n{3,}/g, '\n\n'));
  console.log(`${C.g}wrote .env.example${C.x} (${schema.vars.length} vars documented)`);
  process.exit(0);
}

function wrap(text, width) {
  const words = text.split(/\s+/);
  const out = [];
  let line = '';
  for (const w of words) {
    if ((line + ' ' + w).trim().length > width) { out.push(line.trim()); line = w; }
    else line += ' ' + w;
  }
  if (line.trim()) out.push(line.trim());
  return out;
}

// ── --remote: diff the three systems by NAME ────────────────────────────────
function listRemote() {
  const result = { convexProd: null, convexDev: null, vercel: {}, errors: [] };

  const convex = (flag) => {
    try {
      const out = execFileSync('npx', ['convex', 'env', 'list', ...flag], {
        cwd: APP, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 120_000,
      });
      // `convex env list` prints NAME=value; keep names only.
      return new Set(out.split('\n').map((l) => l.split('=')[0].trim()).filter((n) => /^[A-Z_][A-Z0-9_]*$/.test(n)));
    } catch (e) {
      result.errors.push(`convex env list ${flag.join(' ') || '(dev)'}: ${String(e.message).split('\n')[0]}`);
      return null;
    }
  };
  result.convexProd = convex(['--prod']);
  result.convexDev = convex([]);

  for (const envName of ['production', 'preview', 'development']) {
    try {
      const out = execFileSync('vercel', ['env', 'ls', envName], {
        cwd: APP, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 120_000,
      });
      result.vercel[envName] = new Set(
        out.split('\n').map((l) => (l.trim().match(/^([A-Z_][A-Z0-9_]*)\b/) || [])[1]).filter(Boolean),
      );
    } catch (e) {
      const msg = String(e.message).split('\n')[0];
      result.vercel[envName] = null;
      result.errors.push(
        /ENOENT/.test(msg)
          ? `vercel CLI not installed — run \`npm i -g vercel\` to check Vercel envs`
          : `vercel env ls ${envName}: ${msg}`,
      );
    }
  }
  return result;
}

const COL_TO_HOME = {
  'convex:prod': 'convex:prod',
  'convex:dev': 'convex:dev',
  'vercel:prod': 'vercel:production',
  'vercel:prev': 'vercel:preview',
  'vercel:dev': 'vercel:development',
  local: 'local',
};
const homeFor = (col) => COL_TO_HOME[col] ?? col;

const mark = (set, name) => (set === null ? `${C.d}?${C.x}` : set.has(name) ? `${C.g}✓${C.x}` : `${C.r}✗${C.x}`);

if (has('--remote')) {
  const r = listRemote();
  const local = localEnv();
  const cols = ['convex:prod', 'convex:dev', 'vercel:prod', 'vercel:prev', 'vercel:dev', 'local'];
  console.log(`\n${C.b}env parity${C.x}  ${C.d}(names only — no values are read or printed)${C.x}\n`);
  console.log(`${'variable'.padEnd(26)}${cols.map((c) => c.padEnd(13)).join('')}`);
  console.log('-'.repeat(26 + cols.length * 13));

  let drift = 0;
  for (const v of schema.vars) {
    if (v.platformProvided || v.homes.length === 0) continue;
    const present = {
      'convex:prod': r.convexProd, 'convex:dev': r.convexDev,
      'vercel:prod': r.vercel.production, 'vercel:prev': r.vercel.preview,
      'vercel:dev': r.vercel.development,
      local: new Set(Object.keys(local)),
    };
    const expectedIn = (col) => {
      if (col === 'local') return v.homes.includes('local') || v.homes.some((h) => h.startsWith('local:'));
      if (col === 'convex:prod') return v.homes.includes('convex:prod');
      if (col === 'convex:dev') return v.homes.includes('convex:dev');
      if (col === 'vercel:prod') return v.homes.includes('vercel:production');
      if (col === 'vercel:prev') return v.homes.includes('vercel:preview');
      if (col === 'vercel:dev') return v.homes.includes('vercel:development');
      return false;
    };
    const cells = cols.map((col) => {
      const set = present[col];
      if (!expectedIn(col)) return `${C.d}·${C.x}`.padEnd(13 + C.d.length + C.x.length - 1);
      if (set === null) return `${C.d}?${C.x}`.padEnd(13 + C.d.length + C.x.length - 1);
      if (set.has(v.name)) return `${C.g}✓${C.x}`.padEnd(13 + C.g.length + C.x.length - 1);
      // Optional here — either globally optional, or not required in THIS home.
      if (!isRequiredIn(v, homeFor(col))) return `${C.y}opt${C.x}`.padEnd(13 + C.y.length + C.x.length - 1);
      drift++;
      return `${C.r}MISSING${C.x}`.padEnd(13 + C.r.length + C.x.length - 1);
    });
    console.log(`${v.name.padEnd(26)}${cells.join('')}`);
  }

  console.log(`\n${C.d}✓ present   MISSING required but absent   opt optional and absent   · not expected here   ? could not check${C.x}`);

  const sync = schema.vars.filter((v) => v.mustMatchAcrossHomes);
  if (sync.length) {
    console.log(`\n${C.b}must-match vars${C.x} ${C.d}(sha256 prefix of the LOCAL value, for manual comparison${C.x}`);
    console.log(`${C.d}against the Convex/Vercel dashboards — remote values are never fetched)${C.x}`);
    for (const v of sync) {
      const val = localEnv()[v.name];
      console.log(`  ${v.name.padEnd(26)} ${val ? `sha256:${hash(val)}` : `${C.y}not set locally${C.x}`}`);
    }
  }

  if (r.errors.length) {
    console.log(`\n${C.y}could not check everything:${C.x}`);
    for (const e of [...new Set(r.errors)]) console.log(`  - ${e}`);
  }

  if (has('--ci')) {
    if (drift > 0) { console.error(`\n${C.r}env drift: ${drift} required var(s) missing from a declared home.${C.x}`); process.exit(1); }
    console.log(`\n${C.g}no drift in the homes that could be checked.${C.x}`);
  }
  process.exit(0);
}

// ── default: validate the local env ────────────────────────────────────────
const scopeIdx = args.indexOf('--scope');
const scope = scopeIdx >= 0 ? args[scopeIdx + 1] : null;
const env = localEnv();
const problems = [];
const warnings = [];

for (const v of schema.vars) {
  if (v.platformProvided || v.homes.length === 0) continue;
  if (scope === 'server' && (v.public || !v.homes.some((h) => h.startsWith('vercel:')))) continue;
  if (scope === 'client' && !v.public) continue;
  // Vars that only live on the Convex deployment are not expected in a local file.
  const localExpected = v.homes.includes('local') || v.homes.some((h) => h.startsWith('local:'));
  const val = env[v.name];

  if (val === undefined || val === '') {
    if (localExpected && isRequired(v)) problems.push(`${v.name} is not set (${v.note ? v.note.split('.')[0] : 'required'})`);
    continue;
  }
  if (v.pattern && !new RegExp(v.pattern).test(val)) problems.push(`${v.name} does not match ${v.pattern}`);
  if (v.enum && !v.enum.includes(val)) problems.push(`${v.name} must be one of ${v.enum.join(' | ')}`);
  if (v.minLength && val.length < v.minLength) problems.push(`${v.name} must be at least ${v.minLength} characters`);
  if (v.pairedWith) {
    const pair = schema.vars.find((x) => x.name === v.pairedWith);
    const other = env[v.pairedWith];
    if (other !== undefined && other !== val) {
      problems.push(`${v.name} and ${v.pairedWith} must be identical (they are not) — push notifications fail silently when they differ`);
    } else if (other === undefined) {
      // Only a problem if the pair is expected in a LOCAL file. VAPID_PUBLIC_KEY
      // lives only on the Convex deployment, so its absence here is correct and
      // the two halves must be compared in the Convex dashboard instead.
      const pairIsLocal = pair?.homes.some((h) => h === 'local' || h.startsWith('local:'));
      if (pairIsLocal) warnings.push(`${v.name} is set but its pair ${v.pairedWith} is not`);
      else warnings.push(`${v.name} must equal ${v.pairedWith}, which lives on the Convex deployment — compare them there (this check cannot)`);
    }
  }
}

if (warnings.length) {
  console.log(`${C.y}env warnings:${C.x}`);
  for (const w of [...new Set(warnings)]) console.log(`  - ${w}`);
}
if (problems.length) {
  // --warn-only: report but exit 0. Used by `prebuild` until `--remote` shows a
  // clean Vercel env; flip prebuild to strict once it does, so a missing var
  // fails the build with a named error instead of 500-ing at runtime.
  const warnOnly = has('--warn-only');
  const out = warnOnly ? console.warn : console.error;
  out(`${warnOnly ? C.y : C.r}env check ${warnOnly ? 'found problems (warn-only)' : 'failed'}:${C.x}`);
  for (const p of problems) out(`  - ${p}`);
  out(`\nSee .env.example, or run: node scripts/check-env.mjs --write-example`);
  if (!warnOnly) process.exit(1);
}
console.log(`${C.g}env OK${C.x}${scope ? ` (scope: ${scope})` : ''}`);
