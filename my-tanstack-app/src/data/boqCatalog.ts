/** Every catalog item across all room types, de-duplicated by name (for cross-room autocomplete). */
export const getAllCatalogItems = (): BoqCatalogItem[] => {
  const seen = new Set<string>();
  const out: BoqCatalogItem[] = [];
  for (const item of [...Object.values(BOQ_CATALOG_BY_ROOM).flat(), ...BOQ_CATALOG_UNIVERSAL]) {
    const key = item.name.trim().toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
  }
  return out;
};

