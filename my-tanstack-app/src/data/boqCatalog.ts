/** Category to suggest for `item` when it is being added to a room of `roomType`. */
export const adaptCategoryForRoom = (item: { name: string; cat: string }, roomType?: string): string => {
  const own = (roomType ? BOQ_CATALOG_BY_ROOM[roomType] || [] : []).find(
    (c) => c.name.trim().toLowerCase() === item.name.trim().toLowerCase(),
  );
  if (own) return own.cat; // room already defines it explicitly
  const roomFurniture = roomType ? FURNITURE_CATEGORY_BY_ROOM[roomType] : undefined;
  if (roomFurniture && FURNITURE_CATEGORIES.has(item.cat)) return roomFurniture;
  return item.cat;
};

/** Categories most relevant to a room type, for quick-pick chips. */
export const getCategoriesForRoomType = (roomType?: string): string[] => {
  const cats = (roomType ? BOQ_CATALOG_BY_ROOM[roomType] || [] : []).map((c) => c.cat);
  const furniture = roomType ? FURNITURE_CATEGORY_BY_ROOM[roomType] : undefined;
  return Array.from(new Set([...(furniture ? [furniture] : []), ...cats]));
};
